#!/usr/bin/env python3
"""Génère overlay_font.rs : une police Inter Medium en masques alpha, pour écrire
n'importe quel texte sur la Touch Bar sans moteur de police dans le renderer.

Usage : python3 touchbar-font.py crates/t1-touchbar/src/overlay_font.rs
Chaque glyphe a la hauteur de ligne commune et la largeur de son avance (sans crénage).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/opentype/inter/Inter-Medium.otf"
SIZE = 20
CHARS = "".join(chr(c) for c in range(32, 127)) + "àâäçéèêëîïôöùûüÿœÀÂÇÉÈÊËÎÏÔÙÛÜŒ«»’…–—°·"

font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
HEIGHT = ascent + descent


def glyph(ch):
    width = max(1, round(font.getlength(ch)))
    img = Image.new("L", (width, HEIGHT), 0)
    ImageDraw.Draw(img).text((0, 0), ch, fill=255, font=font)
    return width, list(img.getdata())


def main(out):
    lines = [
        "//! Generated by `touchbar-font.py` from Inter Medium 4.1 (SIL OFL 1.1); do not edit by hand.",
        "//! Fixed line height, per-glyph advance width, no kerning.",
        "",
        f"pub(crate) const LINE_HEIGHT: u32 = {HEIGHT};",
        "",
        "/// (character, advance width, `width * LINE_HEIGHT` alpha pixels)",
        "pub(crate) const GLYPHS: &[(char, u32, &[u8])] = &[",
    ]
    for ch in CHARS:
        width, px = glyph(ch)
        literal = "'\\''" if ch == "'" else ("'\\\\'" if ch == "\\" else f"'{ch}'")
        lines.append(f"    ({literal}, {width}, &[{', '.join(map(str, px))}]),")
    lines.append("];")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(CHARS)} glyphes, hauteur {HEIGHT} px")


if __name__ == "__main__":
    main(sys.argv[1])
